from __future__ import annotations


#
# Neither web changes the mode by touching single keys: they delete every network section
# and load the new mode's default configuration. The templates below are copied as they
# are from the firmware (airOS 6: defaultCfg in ubnt.net.js; airOS 8: the default-values
# module of its web). In router mode, "WAN" and "LAN" are replaced by interfaces depending
# on whether the antenna is an access point or a station and has one or two Ethernet
# ports. When saving, each web also makes a few adjustments (see switch_netmode).

